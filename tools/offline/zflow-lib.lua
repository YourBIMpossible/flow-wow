-- Shared by the Z-Flow offline tools (zflow-run.lua, zflow-toc.lua,
-- zflow-structure.lua). Lua 5.1. Loaded with dofile from the same folder.
local L = {}

L.ADDON = "ZFlow"

function L.join(root, rel)
    return (root:gsub("[/\\]+$", "")) .. "/" .. rel
end

function L.readAll(path)
    local f = io.open(path, "rb")
    if not f then return nil end
    local text = f:read("*a")
    f:close()
    return text
end

-- Lines of a text file, without line ends or blank lines.
function L.readLines(path)
    local text = L.readAll(path)
    if not text then return nil end
    local out = {}
    for line in text:gmatch("[^\r\n]+") do out[#out + 1] = line end
    return out
end

-- The manifest as { interface, version, files = { { path, dev } ... } },
-- or nil and what is wrong with it.
function L.manifest(root)
    local path = L.join(root, L.ADDON .. "/manifest.lua")
    local chunk, err = loadfile(path)
    if not chunk then return nil, err end
    local ok, m = pcall(chunk)
    if not ok then return nil, tostring(m) end
    if type(m) ~= "table" or type(m.files) ~= "table" then return nil, path .. ": must return { files = {...} }" end
    local files, seen = {}, {}
    for i, entry in ipairs(m.files) do
        local rel, dev
        if type(entry) == "string" then rel = entry
        elseif type(entry) == "table" then rel, dev = entry[1], entry.dev and true or false end
        if type(rel) ~= "string" or rel == "" or rel:find("\\") then
            return nil, path .. ": entry " .. i .. " is not a path with forward slashes"
        end
        if seen[rel:lower()] then return nil, path .. ": " .. rel .. " is listed twice" end
        seen[rel:lower()] = true
        files[#files + 1] = { path = rel, dev = dev or false }
    end
    -- optionalDeps: more add-ons named on the TOC's OptionalDeps line after
    -- the predecessor (load them first when present; never required).
    local optional = {}
    if type(m.optionalDeps) == "table" then
        for i, name in ipairs(m.optionalDeps) do
            if type(name) ~= "string" or not name:find("^[%w_%-]+$") then
                return nil, path .. ": optionalDeps entry " .. i .. " is not an add-on name"
            end
            optional[#optional + 1] = name
        end
    end
    return { interface = m.interface, version = m.version, files = files, optionalDeps = optional }
end

-- ns.id, read by loading Core/Identity.lua alone.
function L.identity(root)
    local chunk, err = loadfile(L.join(root, L.ADDON .. "/Core/Identity.lua"))
    if not chunk then return nil, err end
    local ns = {}
    local ok, e = pcall(chunk, L.ADDON, ns)
    if not ok then return nil, tostring(e) end
    if type(ns.id) ~= "table" then return nil, "Core/Identity.lua did not set ns.id" end
    return ns.id
end

-- The TOC text for this manifest and identity ("\n" line ends).
function L.tocText(m, id)
    local lines = {
        "## Interface: " .. tostring(m.interface),
        "## Title: " .. id.title,
        "## Notes: " .. id.notes,
        "## Version: " .. tostring(m.version),
        "## SavedVariables: " .. id.accountDB,
        "## SavedVariablesPerCharacter: " .. id.charDB,
        "## OptionalDeps: " .. table.concat({ id.predecessor, unpack(m.optionalDeps or {}) }, ", "),
        "# Generated by tools/zflow-toc.ps1 from manifest.lua and Core/Identity.lua. Do not edit.",
        "",
    }
    for _, f in ipairs(m.files) do
        if not f.dev then lines[#lines + 1] = (f.path:gsub("/", "\\")) end
    end
    return table.concat(lines, "\n") .. "\n"
end

return L
